from archive.history import get_report
from archive.publication import publish
from control.changeover import change
from intake.completeness import check_lane_interval
from intake.receipts import read_lane_receipts, read_lane_seals
from recorder.actions import read_action_result
from recorder.slots import active_slots
from tests.fixture import ColdChainCase


class ChangeoverTests(ColdChainCase):
    def test_sampling_before_enable(self):
        shift = self.open()
        new = self.rule('night', threshold=8500)
        self.sample(*([7000] * 42))
        self.device.hold_requests.add('enable')
        pending = change(self.db, 'rec', new, 'switch', self.device)
        self.assertIsNone(pending.enabled_after)
        self.assertIsNone(pending.boundary)
        self.assertEqual([slot.lane for slot in active_slots(self.source, 'rec')], [shift.initial_lane])
        self.assertIsNone(read_action_result(self.source, 'rec', 'switch', 'retire'))
        at_43 = self.sample(9300)
        self.assertEqual([(item.lane, item.reading.source_seq) for item in at_43], [(shift.initial_lane, 43)])
        enabled = self.device.perform('rec', 'switch', 'enable')
        self.assertEqual(enabled.boundary, 43)
        op = change(self.db, 'rec', new, 'switch', self.device)
        self.assertEqual((op.enabled_after, op.retired_through, op.boundary), (43, 43, 43))
        self.deliver(*self.seal(), *at_43)
        report = publish(self.db, 'shift', 'after-delay')
        self.assertEqual(report.alerts.readings, at_43)
        self.assertEqual(report.alerts.count, 1)

    def test_lost_reply_and_conflicting_operation(self):
        shift = self.open(self.rule(threshold=8500))
        new = self.rule('night', threshold=9000)
        self.sample(*([7000] * 41))
        self.device.hide_results.add('enable')
        pending = change(self.db, 'rec', new, 'switch', self.device)
        self.assertIsNone(pending.enabled_after)
        actual = read_action_result(self.source, 'rec', 'switch', 'enable')
        self.assertEqual(actual.boundary, 41)
        self.assertIsNone(read_action_result(self.source, 'rec', 'switch', 'retire'))
        self.assertEqual({slot.lane for slot in active_slots(self.source, 'rec')}, {shift.initial_lane, actual.lane})
        self.assertEqual(change(self.db, 'rec', new, 'switch', self.device), pending)
        with self.assertRaises(ValueError):
            change(self.db, 'rec', new, 'other', self.device)
        with self.assertRaises(ValueError):
            change(self.db, 'rec', shift.initial_lane.rule, 'switch', self.device)
        old_item, = self.sample(8600)
        old_duplicate, new_item = self.sample(9300)
        self.assertEqual(old_duplicate.reading, new_item.reading)
        self.assertEqual(new_item.lane.rule, new)
        self.deliver(new_item)
        self.assertEqual(read_lane_receipts(self.db, actual.lane), (new_item,))
        self.sample(7000)
        self.reopen()
        self.device.hide_results.clear()
        op = change(self.db, 'rec', new, 'switch', self.device)
        self.assertEqual((op.enabled_after, op.retired_through, op.boundary), (41, 44, 41))
        self.assertEqual(read_action_result(self.source, 'rec', 'switch', 'enable'), actual)
        self.reopen()
        self.assertEqual(change(self.db, 'rec', new, 'switch', self.device), op)
        final, = self.sample(9100)
        self.deliver(*self.seal(), final, old_duplicate, old_item)
        report = publish(self.db, 'shift', 'overlap')
        self.assertEqual(report.alerts.readings, (new_item, final))
        self.assertEqual((report.alerts.count, report.alerts.peak_mc), (2, 9300))
        self.assertEqual(report.changes[0].boundary, 41)

    def test_early_seal_waits_for_missing_overlap_read(self):
        self.open(self.rule(threshold=8500))
        new = self.rule('night', threshold=9000)
        self.rule('later', threshold=10000)
        self.sample(*([7000] * 41))
        self.device.hold_requests.add('retire')
        change(self.db, 'rec', new, 'switch', self.device)
        old_only, = self.sample(8600)
        old_copy, new_copy = self.sample(9300)
        self.sample(7000)
        self.device.perform('rec', 'switch', 'retire')
        op = change(self.db, 'rec', new, 'switch', self.device)
        self.assertEqual((op.enabled_after, op.retired_through, op.boundary), (41, 44, 41))
        final, = self.sample(9100)
        old_seal, new_seal = self.seal()
        self.assertEqual((old_seal.cutoff, old_seal.last_delivery), (44, 2))
        self.assertEqual((new_seal.cutoff, new_seal.last_delivery), (45, 2))
        self.deliver(new_seal, old_seal, final, old_copy, old_only)
        self.assertEqual(read_lane_seals(self.db, new_copy.lane), (new_seal,))
        self.assertIsNone(publish(self.db, 'shift', 'early'))
        self.assertIsNone(get_report(self.db, 'early'))
        self.deliver(new_copy)
        report = publish(self.db, 'shift', 'early')
        self.assertEqual(report.alerts.readings, (new_copy, final))
        self.assertEqual([item.reading.source_seq for item in report.alerts.readings], [43, 45])
        self.assertEqual((report.alerts.count, report.alerts.peak_mc), (2, 9300))
        self.reopen()
        self.assertEqual(change(self.db, 'rec', new, 'switch', self.device), op)
        self.assertEqual(publish(self.db, 'shift', 'early'), report)

    def test_single_lane_hits_obey_reported_boundary(self):
        self.open(self.rule(point='west', threshold=8500))
        new = self.rule('night', point='east', threshold=9000)
        self.sample(*([7000] * 41))
        self.device.hold_requests.add('retire')
        change(self.db, 'rec', new, 'switch', self.device)
        old, = self.sample(8600)
        new_overlap, = self.sample(9300, point='east')
        self.sample(7000)
        self.device.perform('rec', 'switch', 'retire')
        op = change(self.db, 'rec', new, 'switch', self.device)
        last, = self.sample(9100, point='east')
        self.deliver(*self.seal(), old, new_overlap, last)
        report = publish(self.db, 'shift', 'points')
        self.assertEqual((op.enabled_after, op.retired_through), (41, 44))
        self.assertEqual(report.changes[0].boundary, 41)
        self.assertEqual(report.alerts.readings, (new_overlap, last))
        self.assertEqual([item.reading.point for item in report.alerts.readings], ['east', 'east'])

    def test_equal_boundaries(self):
        self.open(self.rule(threshold=8500))
        first, = self.sample(8700)
        op = change(self.db, 'rec', self.rule('night'), 'instant', self.device)
        self.assertEqual((op.enabled_after, op.retired_through, op.boundary), (1, 1, 1))
        second, = self.sample(9000)
        self.deliver(*self.seal(), second, first)
        self.assertEqual(publish(self.db, 'shift', 'instant').alerts.readings, (first, second))

    def test_serial_slot_reuse_preserves_old_lane(self):
        first_rule = self.rule(threshold=8000)
        second_rule = self.rule('night', threshold=9000)
        third_rule = self.rule('morning', threshold=10000)
        self.open(first_rule)
        first, = self.sample(8100)
        change_one = change(self.db, 'rec', second_rule, 'one', self.device)
        second, = self.sample(9100)
        change_two = change(self.db, 'rec', third_rule, 'two', self.device)
        third, = self.sample(10100)
        self.assertEqual((first.lane.slot, third.lane.slot), (0, 0))
        self.assertEqual([item.lane.generation for item in (first, second, third)], [0, 1, 2])
        self.assertEqual(self.deliver(third, first, second)[1].item, first)
        self.deliver(*self.seal())
        report = publish(self.db, 'shift', 'three-lanes')
        self.assertEqual([entry.boundary for entry in report.changes], [1, 2])
        self.assertEqual(report.alerts.readings, (first, second, third))
        self.assertEqual(change(self.db, 'rec', second_rule, 'one', self.device), change_one)
        self.assertEqual(change(self.db, 'rec', third_rule, 'two', self.device), change_two)

    def test_interior_gap_waits_after_final_delivery(self):
        self.open()
        self.sample(7000)
        op = change(self.db, 'rec', self.rule('night'), 'switch', self.device)
        first, middle, last = self.sample(9100, 9200, 9300)
        self.deliver(*self.seal(), last, first)
        evidence = check_lane_interval(self.db, op.new_lane, 2, 4, active_after=1)
        self.assertFalse(evidence.complete)
        self.assertEqual(evidence.first_missing_delivery, 2)
        self.assertIsNone(publish(self.db, 'shift', 'gap'))
        self.assertIsNone(get_report(self.db, 'gap'))
        self.deliver(middle)
        self.assertEqual(publish(self.db, 'shift', 'gap').alerts.readings, (first, middle, last))

    def test_missing_retired_suffix_does_not_block_owned_prefix(self):
        self.open()
        first, = self.sample(7000, 9300)
        new = self.rule('night')
        self.device.hold_requests.add('retire')
        change(self.db, 'rec', new, 'switch', self.device)
        old_gap, new_first = self.sample(9400)
        old_last, new_last = self.sample(9500)
        self.device.perform('rec', 'switch', 'retire')
        op = change(self.db, 'rec', new, 'switch', self.device)
        self.assertEqual((op.boundary, op.retired_through), (2, 4))
        self.deliver(*self.seal(), first, old_last, new_first, new_last)
        self.assertEqual([item.delivery_no for item in read_lane_receipts(self.db, first.lane)], [1, 3])
        self.assertEqual((old_gap.delivery_no, old_gap.reading.source_seq), (2, 3))
        evidence = check_lane_interval(self.db, first.lane, 1, 2, active_after=0)
        self.assertTrue(evidence.complete)
        self.assertEqual(evidence.covering_seal.cutoff, 4)
        report = publish(self.db, 'shift', 'outside')
        self.assertEqual(report.alerts.readings, (first, new_first, new_last))

    def test_pending_change_blocks_closed_shift_until_confirmed(self):
        self.open()
        new = self.rule('night')
        first, = self.sample(9100)
        self.device.hide_results.add('enable')
        change(self.db, 'rec', new, 'switch', self.device)
        old_copy, new_copy = self.sample(9300)
        self.deliver(*self.seal(), first, old_copy, new_copy)
        self.assertIsNone(publish(self.db, 'shift', 'pending'))
        self.device.hide_results.clear()
        completed = change(self.db, 'rec', new, 'switch', self.device)
        self.assertEqual((completed.boundary, completed.retired_through), (1, 2))
        self.assertEqual(publish(self.db, 'shift', 'pending').alerts.readings, (first, new_copy))
